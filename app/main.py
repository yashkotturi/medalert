# Fault injection for reliability testing: fraction of requests that fail.
# Keep at 0 normally. Set e.g. MEDALERT_CHAOS_ERROR_RATE=0.2 to simulate an outage.
CHAOS_ERROR_RATE = float(os.getenv("MEDALERT_CHAOS_ERROR_RATE", "0"))


@asynccontextmanager
async def lifespan(_: FastAPI):
    init_db()  # create tables + seed data on startup
    yield


app = FastAPI(
    title="MedAlert",
    description="Hospital bed and medicine availability service",
    version="1.0.0",
    lifespan=lifespan,
)


@app.middleware("http")
async def log_and_time_requests(request: Request, call_next):
    start = time.perf_counter()
    if CHAOS_ERROR_RATE and request.url.path != "/health":
        if random.random() < CHAOS_ERROR_RATE:
            response = JSONResponse({"detail": "Injected failure (chaos test)"}, 500)
            _log_request(request, response.status_code, start)
            return response
    try:
        response = await call_next(request)
    except Exception:
        log.exception("unhandled error")
        response = JSONResponse({"detail": "Internal server error"}, status_code=500)
    _log_request(request, response.status_code, start)
    return response


def _log_request(request: Request, status: int, start: float) -> None:
    log.info(json.dumps({
        "ts": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "method": request.method,
        "path": request.url.path,
        "status": status,
        "duration_ms": round((time.perf_counter() - start) * 1000, 2),
    }))


# ---------- Security ----------
def require_api_key(
    x_api_key: str | None = Header(default=None),
    x_actor: str = Header(default="unknown"),
) -> str:
    """Write endpoints need an API key. Returns who is acting (for the audit log).

    Authentication = proving who you are (the key).
    Authorization = what you may do (here: only key holders can write).
    """
    if x_api_key != config.API_KEY:
        raise HTTPException(status_code=401, detail="Invalid or missing API key")
    return x_actor


# ---------- Helpers ----------
def _ward(row) -> Ward:
    pct = round(row["occupied_beds"] / row["total_beds"] * 100, 1)
    return Ward(
        id=row["id"],
        name=row["name"],
        total_beds=row["total_beds"],
        occupied_beds=row["occupied_beds"],
        free_beds=row["total_beds"] - row["occupied_beds"],
        occupancy_pct=pct,
        near_full=pct >= config.NEAR_FULL_THRESHOLD,
    )


def _medicine(row) -> Medicine:
    return Medicine(**dict(row), low_stock=row["quantity"] < row["min_quantity"])


# ---------- Health ----------
@app.get("/health", tags=["ops"])
def health():
    """Liveness + dependency check. Monitors and Kubernetes probes call this."""
    try:
        with get_conn() as conn:
            conn.execute("SELECT 1")
    except Exception as exc:  # database unreachable -> service is NOT healthy
        raise HTTPException(status_code=503, detail=f"database error: {exc}") from exc
    return {"status": "ok", "database": "ok", "version": app.version}


# ---------- Wards ----------
@app.get("/wards", response_model=list[Ward], tags=["beds"])
def list_wards():
    with get_conn() as conn:
        rows = conn.execute("SELECT * FROM wards ORDER BY name").fetchall()
    return [_ward(r) for r in rows]


@app.get("/wards/{ward_id}", response_model=Ward, tags=["beds"])
def get_ward(ward_id: int):
    with get_conn() as conn:
        row = conn.execute("SELECT * FROM wards WHERE id = ?", (ward_id,)).fetchone()
    if not row:
        raise HTTPException(404, "Ward not found")
    return _ward(row)


@app.patch("/wards/{ward_id}", response_model=Ward, tags=["beds"])
def update_ward(ward_id: int, body: WardUpdate, actor: str = Depends(require_api_key)):
    with get_conn() as conn:
        row = conn.execute("SELECT * FROM wards WHERE id = ?", (ward_id,)).fetchone()
        if not row:
            raise HTTPException(404, "Ward not found")
        if body.occupied_beds > row["total_beds"]:
            raise HTTPException(400, f"Ward only has {row['total_beds']} beds")
        conn.execute(
            "UPDATE wards SET occupied_beds = ? WHERE id = ?",
            (body.occupied_beds, ward_id),
        )
        audit(conn, actor, "update_ward",
              f"{row['name']}: {row['occupied_beds']} -> {body.occupied_beds}")
        row = conn.execute("SELECT * FROM wards WHERE id = ?", (ward_id,)).fetchone()
    return _ward(row)


