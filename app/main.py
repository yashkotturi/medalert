@app.get("/medicines/low-stock", response_model=list[Medicine], tags=["stock"])
def low_stock():
    with get_conn() as conn:
        rows = conn.execute(
            "SELECT * FROM medicines WHERE quantity < min_quantity ORDER BY name"
        ).fetchall()
    return [_medicine(r) for r in rows]


@app.patch("/medicines/{medicine_id}", response_model=Medicine, tags=["stock"])
def update_stock(medicine_id: int, body: StockUpdate,
                 actor: str = Depends(require_api_key)):
    with get_conn() as conn:
        row = conn.execute(
            "SELECT * FROM medicines WHERE id = ?", (medicine_id,)
        ).fetchone()
        if not row:
            raise HTTPException(404, "Medicine not found")
        new_qty = row["quantity"] + body.change
        if new_qty < 0:
            raise HTTPException(400, f"Only {row['quantity']} {row['unit']} in stock")
        conn.execute(
            "UPDATE medicines SET quantity = ? WHERE id = ?", (new_qty, medicine_id)
        )
        audit(conn, actor, "update_stock",
              f"{row['name']}: {row['quantity']} -> {new_qty}")
        row = conn.execute(
            "SELECT * FROM medicines WHERE id = ?", (medicine_id,)
        ).fetchone()
    return _medicine(row)


# ---------- Incidents (ITSM) ----------
@app.get("/incidents", response_model=list[Incident], tags=["incidents"])
def list_incidents(status: str | None = None):
    query, params = "SELECT * FROM incidents", ()
    if status:
        query, params = query + " WHERE status = ?", (status,)
    with get_conn() as conn:
        rows = conn.execute(query + " ORDER BY priority, id DESC", params).fetchall()
    return [Incident(**dict(r)) for r in rows]


@app.post("/incidents", response_model=Incident, status_code=201, tags=["incidents"])
def create_incident(body: IncidentCreate, actor: str = Depends(require_api_key)):
    with get_conn() as conn:
        cur = conn.execute(
            "INSERT INTO incidents (title, priority, details) VALUES (?, ?, ?)",
            (body.title, body.priority, body.details),
        )
        audit(conn, actor, "create_incident", f"#{cur.lastrowid} [{body.priority}] {body.title}")
        row = conn.execute(
            "SELECT * FROM incidents WHERE id = ?", (cur.lastrowid,)
        ).fetchone()
    return Incident(**dict(row))


@app.patch("/incidents/{incident_id}", response_model=Incident, tags=["incidents"])
def update_incident(incident_id: int, body: IncidentUpdate,
                    actor: str = Depends(require_api_key)):
    with get_conn() as conn:
        cur = conn.execute(
            "UPDATE incidents SET status = ?, updated_at = datetime('now') WHERE id = ?",
            (body.status, incident_id),
        )
        if cur.rowcount == 0:
            raise HTTPException(404, "Incident not found")
        audit(conn, actor, "update_incident", f"#{incident_id} -> {body.status}")
        row = conn.execute(
            "SELECT * FROM incidents WHERE id = ?", (incident_id,)
        ).fetchone()
    return Incident(**dict(row))


@app.get("/audit", tags=["ops"])
def audit_log(limit: int = 50, _: str = Depends(require_api_key)):
    """Audit trail. Protected: who-did-what is sensitive."""
    with get_conn() as conn:
        rows = conn.execute(
            "SELECT * FROM audit_log ORDER BY id DESC LIMIT ?", (min(limit, 500),)
        ).fetchall()
